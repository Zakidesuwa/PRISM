/** Sub-routes keep their section highlighted (/admin/cooperative/12 -> Cooperative). */
function isActive(pathname: string, href: string) {
  if (href === '/admin') return pathname === '/admin';
  return pathname === href || pathname.startsWith(`${href}/`);
}

